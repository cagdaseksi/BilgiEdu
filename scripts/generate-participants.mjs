import {
  readdirSync,
  readFileSync,
  writeFileSync,
  mkdirSync,
  lstatSync,
  existsSync,
} from 'node:fs';
import { join, resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const dir = join(root, 'src/participants');
const entries = readdirSync(dir, { withFileTypes: true })
  .filter(item => item.isDirectory())
  .sort((a, b) => a.name.localeCompare(b.name));
const ids = new Set();
const rows = entries.map((entry, index) => {
  if (!/^[a-z][a-z0-9-]*$/.test(entry.name)) {
    throw new Error('Invalid participant directory: ' + entry.name);
  }
  const folder = join(dir, entry.name);
  const manifest = JSON.parse(
    readFileSync(join(folder, 'participant.json'), 'utf8'),
  );
  if (manifest.id !== entry.name || ids.has(manifest.id)) {
    throw new Error('Invalid/duplicate participant id: ' + manifest.id);
  }
  ids.add(manifest.id);
  for (const key of ['name', 'gameTitle']) {
    if (
      typeof manifest[key] !== 'string' ||
      !manifest[key].trim() ||
      /[^\x20-\x7e]/.test(manifest[key]) ||
      manifest[key].length > 80
    ) {
      throw new Error('Invalid ' + key + ': ' + entry.name);
    }
  }
  if (!/^#[0-9a-f]{6}$/i.test(manifest.accent)) {
    throw new Error('Invalid accent: ' + entry.name);
  }
  if (
    !existsSync(join(folder, 'Screen.tsx')) ||
    lstatSync(join(folder, 'Screen.tsx')).isSymbolicLink()
  ) {
    throw new Error('Missing/invalid Screen.tsx: ' + entry.name);
  }
  return { manifest, index, name: entry.name };
});
mkdirSync(join(root, 'src/generated'), { recursive: true });
const imports = rows
  .map(
    row =>
      'import Screen' +
      row.index +
      " from '../participants/" +
      row.name +
      "/Screen';",
  )
  .join('\n');
const content = rows
  .map(
    row =>
      '  {...' +
      JSON.stringify(row.manifest) +
      ', Screen: Screen' +
      row.index +
      '},',
  )
  .join('\n');
writeFileSync(
  join(root, 'src/generated/participants.ts'),
  "// Generated by npm run participants. Do not edit.\nimport type {Participant} from '../shared/types';\n" +
    imports +
    '\n\nexport const participants: Participant[] = [\n' +
    content +
    '\n];\n',
);
console.log('Registered ' + rows.length + ' participant(s).');
